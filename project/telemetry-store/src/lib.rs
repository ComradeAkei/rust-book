//! Сквозной проект «станция телеметрии», шаг главы 15: приёмник на хосте
//! хранит измерения в памяти и умеет отвечать на запросы по диапазону
//! времени, не трогая кучу в установившемся режиме.
//!
//! В главе 13 [`telemetry_frame::stream::Frames`] разобрал поток байт на
//! кадры. Здесь поток кадров оседает в хранилище: у каждого датчика —
//! кольцо последних измерений фиксированной длины. Пока датчики те же и
//! кольца заполнены, [`Store::ingest`] не делает ни одного обращения к
//! распределителю: место под кольцо выделено один раз, а новое измерение
//! вытесняет самое старое на том же буфере. Это свойство и проверяет
//! [`alloc`]: аллокатор-счётчик, который видно из любого потока.
//!
//! Крейт — хостовый (`std`), в отличие от `no_std`-крейта формата кадра:
//! `HashMap` и `VecDeque` живут на куче, которой у прошивки нет.

pub mod alloc;
pub mod store;

pub use alloc::{Counted, Counts};
pub use store::{Ingested, Point, Store, Summary};
