def spsc():
    d = Diagram("SPSC: один пишет, другой читает", "Очередь на четыре слота после push(A) и push(B): tail равен нулю и указывает на A; head равен двум и указывает на следующий свободный слот. Вместимость равна трём, один слот должен оставаться пустым.", height=620)
    d.text(190, 133, ["Читатель: tail = 0", "следующим заберёт A"], "body", "middle")
    d.text(610, 133, ["Писатель: head = 2", "следующим положит C"], "body", "middle")
    for i, (value, tone) in enumerate((("A", "blue"), ("B", "blue"), ("пусто", "green"), ("пусто", "gray"))):
        x = 110 + i * 210
        d.rect(x, 230, 160, 105, tone)
        d.text(x + 80, 363, f"слот {i}", "small", "middle")
        d.text(x + 80, 292, value, "label", "middle")
    d.arrow(190, 177, 190, 230, None, "blue")
    d.arrow(610, 177, 610, 230, None, "green")
    d.path("M 900 285 L 950 285 L 950 385 L 65 385 L 65 285 L 110 285")
    d.text(500, 416, "После слота 3 индекс снова становится 0", "body", "middle")
    d.box(40, 452, 440, 98, "Пустая очередь", ["head == tail"], "gray")
    d.box(520, 452, 440, 98, "Полная очередь", ["(head + 1) % N == tail"], "orange")
    d.note("При N = 4 помещаются 3 элемента; положение пустого слота меняется.")
    return d.save("advanced-spsc.svg")


