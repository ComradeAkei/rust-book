//! Задача A: какие элементы библиотеки из `code/ch08/fragments/a.rs`
//! видны из мест ⟨1⟩–⟨6⟩.

// ANCHOR: answers
/// Строка на элемент в порядке из условия, по символу на место ⟨1⟩–⟨6⟩:
/// `+` — обращение компилируется, `-` — нет.
pub fn answers() -> [&'static str; 8] {
    [
        // CLOCK_HZ: приватное видно в своём модуле и во всех его потомках,
        // а модуль здесь — корень крейта.
        "+++++-",
        // Uart::baud: pub(crate) — весь крейт, но не другой крейт.
        "+++++-",
        // Uart::fifo: приватное поле видно только в hal::uart.
        "--+---",
        // Uart::reset: pub(super) из hal::uart — это hal и его потомки.
        "-+++--",
        // dma::start: pub внутри приватного модуля. Путь к функции идёт
        // через hal::dma, а его видно только из hal и потомков hal.
        "-+++--",
        // DmaChannel: реэкспорт открывает тип по новому пути всем.
        "++++++",
        // DmaChannel.0: поле осталось приватным для hal::dma, реэкспорт
        // открывает имя типа, а не его поля.
        "---+--",
        // app::render: приватная функция видна только в app.
        "----+-",
    ]
}
// ANCHOR_END: answers
