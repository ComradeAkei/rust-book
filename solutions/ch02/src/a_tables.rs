//! Задача 2.A: где LLVM строит таблицу переходов.

use ch02::task_a::Lowering;

// ANCHOR: answers
/// Предсказания для функций из `code/ch02/src/task_a.rs`, по порядку.
pub const PREDICTIONS: [Option<Lowering>; 5] = [
    // ch02a_method: значения возвращаются константами, но таблица значений
    // нужна плотная (не меньше 40 %), а здесь 7 из 18. Остаётся таблица
    // переходов: для неё хватает 10 %.
    Some(Lowering::JumpTable),
    // ch02a_flash_time: у перечисления четыре значения-степени двойки.
    // Номер бита (tzcnt) превращает их в 0..4, и дальше таблица значений.
    Some(Lowering::MemoryTable),
    // ch02a_uart_reg: адреса идут с шагом 4. Вычитание базы и поворот на
    // два бита дают 0..4, ответ — это число плюс 1.
    Some(Lowering::Formula),
    // ch02a_digits: диапазоны, а не отдельные значения: таблица на 10⁴
    // элементов бессмысленна, остаются сравнения.
    Some(Lowering::Compares),
    // ch02a_level_letter: пять значений по 8 бит помещаются в 64-битный
    // регистр, нужный байт достаёт сдвиг на 8 · уровень.
    Some(Lowering::RegisterTable),
];

/// Наименьшее число ветвей, при котором LLVM строит таблицу переходов.
pub const MIN_CASES: u32 = 4;

/// Наименьшая плотность значений, процентов, при `opt-level` 2 и 3.
pub const MIN_DENSITY: u32 = 10;

/// Наименьшая плотность при `opt-level = "s"` и `"z"`.
pub const MIN_DENSITY_SIZE: u32 = 40;
