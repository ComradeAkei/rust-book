//! Задача 1.C. Проверки переполнения во время выполнения, без `cfg`.

use std::hint::black_box;
use std::panic;

// ANCHOR: probe
/// `true`, если в сборке этого крейта включены проверки переполнения.
#[inline(never)]
pub fn overflow_checks_enabled() -> bool {
    // black_box делает значение непрозрачным для компилятора. Написать
    // `u8::MAX + 1` прямо в замыкании нельзя: линт arithmetic_overflow
    // запрещён по умолчанию и остановит сборку. Через `let x = u8::MAX` он
    // переполнения уже не видит, и функция работает и без black_box: LLVM
    // свернёт сложение в безусловную панику, но не выбросит её.
    let x = black_box(u8::MAX);
    // Результат сложения не нужен, и без проверок оно исчезнет целиком. С
    // проверками остаётся ветка с вызовом паники: это побочный эффект, и
    // выбросить его оптимизатор не вправе.
    panic::catch_unwind(|| x + 1).is_err()
}
// ANCHOR_END: probe
