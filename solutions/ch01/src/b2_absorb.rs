//! Задача 1.B2. Наименьшее положительное `f32` x, при котором `x + 1.0 == x`.

// ANCHOR: analytic
/// Ответ из устройства формата, без перебора.
pub fn smallest_absorbing_analytic() -> f32 {
    // Мантисса f32 хранит 23 бита дроби и скрытую единицу, всего 24 бита.
    // На отрезке [2²⁴, 2²⁵) соседние числа отстоят на 2, и x + 1 попадает
    // ровно посередине между x и x + 2. Ничья округляется к чётной мантиссе,
    // а у 2²⁴ дробная часть нулевая. Ниже 2²⁴ шаг не больше 1, и x + 1
    // всегда ближе к другому числу, чем к x.
    let exponent = f32::MANTISSA_DIGITS; // 24
    let biased = exponent + 127;
    f32::from_bits(biased << 23)
}
// ANCHOR_END: analytic

// ANCHOR: search
/// Тот же ответ перебором битовых шаблонов.
pub fn smallest_absorbing_search() -> f32 {
    // У положительных чисел порядок шаблонов совпадает с порядком значений,
    // поэтому первый найденный шаблон и есть наименьшее число. Шаблоны выше
    // бесконечности — NaN, на них равенство ложно.
    (1..=f32::INFINITY.to_bits())
        .map(f32::from_bits)
        .find(|&x| x + 1.0 == x)
        .expect("бесконечность поглощает единицу, до неё поиск дойдёт")
}
// ANCHOR_END: search
