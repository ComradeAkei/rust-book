/// События каждого фрагмента по порядку: имена `Noisy` при уничтожении и
/// строки из `log`.
pub const PREDICTIONS: [&[&str]; 8] = [
    // №1. Сначала Drop самой Radio, затем её поля в порядке объявления:
    // phy, потом mac. Уничтожение mac — снова «сначала своё, потом поля».
    // Порядок в литерале структуры значения не имеет.
    &["Radio", "phy", "Mac", "tx", "rx"],
    // №2. Присваивание уничтожает b1 сразу. Затенение не уничтожает a1:
    // это вторая переменная с тем же именем. Переменные уничтожаются в
    // обратном порядке объявления: a (вторая), b, a (первая).
    &["b1", "конец", "a2", "b2", "a1"],
    // №3. `let _ = значение` не создаёт переменную: временное значение
    // уничтожается на `;`. Временное `Noisy("tmp")` живёт до конца своей
    // инструкции `let len = ...;`.
    &["_", "tmp", "конец", "_x"],
    // №4. `let _ = g` — образец `_` с местом: ничего не перемещается, g жив
    // до конца функции. Блок `{ h }` — значение, h перемещается во
    // временное, а оно уничтожается на `;`.
    &["после let _ = g", "h", "конец", "g"],
    // №5. drop(v) уничтожает элементы по порядку. `let (_a, _) = t`
    // перемещает только t.0; t.1 остаётся в t. В конце: _a (объявлена
    // позже), затем остаток t.
    &["v0", "v1", "v2", "конец", "t0", "t1"],
    // №6. pass возвращает владение, eat уничтожает аргумент у себя, после
    // своего log. Результат второго pass никому не нужен: временное
    // уничтожается на `;`. Последней уходит _b, в ней лежит "a".
    &["pass", "eat", "c", "pass", "d", "конец", "a"],
    // №7. Паника в explode: из массива готов только x0, его и уничтожают
    // первым, x2 не создан вовсе. Затем раскрутка уничтожает переменные
    // в обратном порядке: _b, v (по порядку элементов), _a.
    &["x0", "b", "v0", "v1", "a"],
    // №8. `if let Some(_n) = s` перемещает значение из s в _n, и оно
    // уничтожается в конце ветки; s уже пуста. Временное значение в
    // `match` живёт до конца всего match, а `_` его не перемещает.
    &["в ветке", "s", "после if let", "ветка match", "m", "конец"],
];
