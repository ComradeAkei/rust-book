//! Задача A: сколько копий `checksum` окажется в бинарнике для каждого из
//! фрагментов `code/ch10/fragments/a1.rs` … `a6.rs`.
//!
//! Копия — отдельное тело функции: символ с адресом в `.text`, в пути
//! которого есть `checksum`, считая и вложенные функции. Несколько имён по
//! одному адресу — одна копия. Сборка: `rustc --edition 2024 -C
//! opt-level=3` и флаги из строки `// rustc:` фрагмента.

// ANCHOR: answers
pub fn copies() -> [usize; 6] {
    [
        // a1: u8 и u16 — две копии; второй вызов с u8 новой не создаёт.
        2,
        // a2: без #[inline(never)] обе копии маленькие, вызываются по разу
        // и встроены в main. Отдельных тел не остаётся.
        0,
        // a3: rustc создал четыре копии: два замыкания (у каждого свой
        // тип, хоть текст одинаковый), функция widen (оба вызова — один
        // тип) и указатель fn(u8) -> u32. После встраивания f у трёх
        // первых одинаковый LLVM IR, и MergeFunctions оставил одну.
        2, // a4: N = 4, 8 и 64. Повтор N = 4 — та же копия.
        3,
        // a5: внешняя обёртка тривиальна и встроена во все четыре места,
        // inner одна на всех.
        1,
        // a6: три копии, но у <u32> и <char> одинаковый машинный код, и
        // компоновщик с --icf=all оставил один из них. LLVM их не слил:
        // загрузка char несёт метаданные !range, и IR различается.
        2,
    ]
}
