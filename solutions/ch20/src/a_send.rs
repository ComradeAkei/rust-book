//! Задача A: `SendBox` — передача владения кучей в другой поток через сырой
//! указатель. Сырой указатель не `Send`, поэтому `Box` нельзя «разобрать» в
//! указатель и перенести в поток без ручного маркера. Здесь показано, когда
//! `unsafe impl Send` обоснован (владение передаётся целиком) и почему
//! `Sync` ставить нельзя (общий доступ к `*mut` из двух потоков — гонка).

// ANCHOR: solution
/// Владеющая обёртка над `*mut T`: единоличный владелец кучи, который можно
/// переместить в другой поток. По `Drop` освобождает выделение.
pub struct SendBox<T> {
    ptr: *mut T,
}

// SAFETY: SendBox — ЕДИНСТВЕННЫЙ владелец выделения (как Box). Перемещение в
// другой поток передаёт владение целиком, второго доступа не остаётся —
// значит, безопасно при `T: Send`.
unsafe impl<T: Send> Send for SendBox<T> {}

// Sync НЕ реализуем намеренно: &SendBox дал бы двум потокам общий доступ к
// одному *mut T без синхронизации — это гонка данных. Владение передаём, а
// не делим.

impl<T> SendBox<T> {
    /// Положить значение в кучу и взять владение указателем.
    pub fn new(value: T) -> Self {
        SendBox { ptr: Box::into_raw(Box::new(value)) }
    }

    /// Забрать значение обратно, вернув владение из кучи.
    pub fn into_inner(self) -> T {
        // SAFETY: ptr получен из Box::into_raw и ещё не освобождался; self
        // поглощается, повторного into_inner не будет. Гасим Drop, чтобы он
        // не освободил память второй раз.
        let ptr = self.ptr;
        core::mem::forget(self);
        *unsafe { Box::from_raw(ptr) }
    }
}

impl<T> Drop for SendBox<T> {
    fn drop(&mut self) {
        // SAFETY: ptr валиден и принадлежит только нам; into_inner гасит Drop
        // через mem::forget, поэтому двойного освобождения нет.
        drop(unsafe { Box::from_raw(self.ptr) });
    }
}
