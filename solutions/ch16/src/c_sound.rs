//! Задача C: безопасная сигнатура — это обещание. Если реализация не может
//! его сдержать, `unsafe` внутри делает API *unsound*: безопасный код,
//! который ему поверил, получает UB, ничего не нарушая со своей стороны.
//! Здесь — честная замена, чья сигнатура не лжёт; ошибочный вариант и UB
//! от него — в задаче C каталога (`tests/ub.rs`).

// ANCHOR: solution
/// Небольшой буфер строки.
pub struct StrBuf {
    inner: String,
}

impl StrBuf {
    pub fn new(s: &str) -> Self {
        StrBuf { inner: s.to_string() }
    }

    /// Взгляд на содержимое. Время жизни результата связано с `&self`:
    /// компилятор не даст использовать его после того, как буфер исчез.
    /// Честная сигнатура — и никакого `unsafe`: `&str` короче или равен
    /// `&self`, обещание выполнимо всегда.
    pub fn view(&self) -> &str {
        &self.inner
    }
}
