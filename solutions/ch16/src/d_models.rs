//! Задача D: одна программа, два вердикта. Stacked Borrows и Tree Borrows
//! по-разному решают, что законно делать с сырым указателем из `&mut`,
//! после того как ту же `&mut` переодолжили заново. Здесь — случай, который
//! Tree Borrows принимает, а Stacked Borrows считает неопределённым
//! поведением. Какая из моделей станет единственной — ещё не решено; код,
//! которому нужна переносимость между ними, так не делает.
//!
//! Эта функция намеренно UB под Stacked Borrows, поэтому её не вызывает ни
//! один обычный тест. Её гоняют под Miri поодиночке (`tests/ub.rs`,
//! `d_tree_ok_stack_ub`): под Tree Borrows — проходит, под Stacked Borrows —
//! Miri сообщает об ошибке.

// ANCHOR: diverge
/// Берём сырой `p` из `&mut r`, пишем через него, затем переодалживаем `r`
/// в новую `&mut r2`, пишем уже через неё — и в конце снова трогаем `p`.
///
/// При обычном запуске итог — `x == 3`. Но законность последней записи
/// через `p` зависит от модели:
///
/// - **Stacked Borrows.** `let p = r` кладёт на стек заёмов метку
///   SharedReadWrite. `let r2 = &mut *r` — это Unique-retag: он снимает со
///   стека всё, что лежит выше `r`, в том числе метку `p`. Запись `*p = 3`
///   идёт по снятой метке — UB (Miri: «tag does not exist in the borrow
///   stack»).
/// - **Tree Borrows.** `p` и `r2` — соседние узлы дерева под `r`; запись
///   через один не вычёркивает другой. Последняя запись через `p` законна.
pub fn tree_ok_stack_ub() -> u8 {
    let mut x = 0u8;
    let r = &mut x;
    let p: *mut u8 = r; // Stacked Borrows: retag SharedReadWrite
    // SAFETY: под Tree Borrows p жив, выровнен, инициализирован, записью
    // владеем единолично. Под Stacked Borrows эта программа UB по построению
    // — в том и задача: показать, где модели расходятся.
    unsafe {
        *p = 1;
    }
    let r2 = &mut *r; // Stacked Borrows: Unique-retag снимает метку p
    *r2 = 2;
    // Под Stacked Borrows метки p на стеке уже нет → UB именно здесь.
    // SAFETY: см. выше — обоснование держится только в Tree Borrows.
    unsafe {
        *p = 3;
    }
    x
}
// ANCHOR_END: diverge
