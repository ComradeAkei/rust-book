//! Задача 5.B: токенизатор конфигурации без выделения памяти.
//!
//! Формат — упрощённый INI: секции `[uart]`, пары `ключ = значение`,
//! комментарии с `#` или `;`. Лексемы — срезы исходного текста.
//!
//! Правила (подробно — в разделе 5.8):
//!
//! - строки делятся `\n`, `\r` в конце строки отбрасывается; пробелы в
//!   начале строки пропускаются;
//! - пустые строки и строки, начинающиеся с `#` или `;`, пропускаются;
//! - `[имя]` — секция; имя непустое, из символов `A–Z a–z 0–9 _ . -`; после
//!   `]` допустимы только пробелы и комментарий;
//! - `ключ = значение` — ключ из тех же символов, пробелы вокруг `=`
//!   допустимы; лексер выдаёт `Key`, затем `Value`;
//! - значение — остаток строки без пробелов по краям; комментарий в
//!   значении начинается с `#` или `;` в начале значения или после пробела
//!   (`a#b` — значение целиком);
//! - значение в кавычках `"…"` — содержимое кавычек, `#` и `;` внутри — его
//!   часть; после закрывающей кавычки — только пробелы и комментарий;
//! - позиция ошибки — номер строки и столбец с 1, столбец в символах:
//!   начало `[` для `UnclosedSection`, первый недопустимый символ имени
//!   (или `]` пустого имени) для `BadName`, место, где ждали `=`, для
//!   `MissingEquals`, открывающая кавычка для `UnclosedQuote`, первый
//!   лишний символ для `TrailingGarbage`.

/// Лексема. Строки внутри — срезы исходного текста, `'a` — его время жизни.
#[derive(Debug, PartialEq, Eq, Clone, Copy)]
pub enum Token<'a> {
    /// `[uart]` → `Section("uart")`.
    Section(&'a str),
    /// `baud = 9600` → `Key("baud")`, затем `Value("9600")`.
    Key(&'a str),
    /// Значение без пробелов по краям и без комментария; у значения в
    /// кавычках — содержимое кавычек.
    Value(&'a str),
}

#[derive(Debug, PartialEq, Eq, Clone, Copy)]
pub enum LexErrorKind {
    /// `[uart` — нет `]`.
    UnclosedSection,
    /// Пустое имя секции или ключа либо символ не из `A–Z a–z 0–9 _ . -`.
    BadName,
    /// После ключа нет `=`.
    MissingEquals,
    /// `"…` без закрывающей кавычки.
    UnclosedQuote,
    /// После `]` или закрывающей кавычки что-то кроме пробелов и комментария.
    TrailingGarbage,
}

/// Ошибка с позицией: строка и столбец с 1, столбец — в символах, не в
/// байтах.
#[derive(Debug, PartialEq, Eq, Clone, Copy)]
pub struct LexError {
    pub line: u32,
    pub col: u32,
    pub kind: LexErrorKind,
}

/// Лексер. Поля придумайте сами; `src` здесь только для того, чтобы `'a`
/// было использовано. Выделять память нельзя: тест считает выделения.
