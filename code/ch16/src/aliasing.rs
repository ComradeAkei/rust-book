//! Раздел 16.5: модели алиасинга. Rust разрешает в каждый момент либо одну
//! `&mut`, либо сколько угодно `&`, и оптимизатор на это опирается. Как
//! именно это правило проверяется на сырых указателях, задают модели
//! Stacked Borrows и Tree Borrows; Miri исполняет обе. Здесь — код,
//! который принимают *обе*; пример, где модели расходятся, — задача D.

// ANCHOR: order
/// Сырой указатель из `&mut` жив, пока ссылку не «перезаимствовали» заново.
/// Правильный порядок: поработать через указатель, а потом снова через
/// ссылку — но не наоборот. Обе модели это принимают.
pub fn raw_then_ref(x: &mut i32) -> i32 {
    let p: *mut i32 = x;
    // SAFETY: p только что получен из x, x жив, между взятием p и этой
    // записью к памяти никто больше не обращается.
    unsafe {
        *p = 10;
    }
    // Дальше работаем через x; p больше не трогаем. Повторное обращение к
    // x «перезаимствует» и отзывает p — поэтому p после этой строки
    // использовать нельзя.
    *x += 5;
    *x
}
// ANCHOR_END: order

// ANCHOR: shared
/// Из `&T` можно наделать сколько угодно сырых `*const T` и читать через
/// них одновременно: пока никто не пишет, это не алиасинг. Обе модели
/// согласны.
pub fn many_readers(x: &i32) -> i32 {
    let p: *const i32 = x;
    let q: *const i32 = x;
    // SAFETY: оба указателя из живого &i32, только чтение, записи нет.
    unsafe { *p + *q }
}
// ANCHOR_END: shared

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn accepted_by_both_models() {
        let mut x = 0;
        assert_eq!(raw_then_ref(&mut x), 15);
        let y = 21;
        assert_eq!(many_readers(&y), 42);
    }
}
