//! Раздел 3.5: `Box::new` с большим массивом.
//!
//! ```text
//! cargo run -p ch03 --example big_box             # переполнение стека
//! cargo run -p ch03 --example big_box --release   # работает
//! ```
//!
//! Аргумент `Box::new` — обычное значение: сначала массив строится на
//! стеке, потом перемещается в кучу. Без оптимизаций 16 МиБ на стеке
//! главного потока (8 МиБ в Linux по умолчанию) не помещаются. В release
//! LLVM видит, что массив нулевой, и сразу просит у аллокатора обнулённую
//! память.

// ANCHOR: big_box
fn main() {
    let buf = Box::new([0u8; 16 << 20]); // 16 МиБ
    println!("выделено {} МиБ по адресу {:p}", buf.len() >> 20, buf.as_ptr());
}
// ANCHOR_END: big_box
