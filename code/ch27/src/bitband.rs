//! Раздел 27.4: bit-band Cortex-M3 и M4. Каждому биту первого мегабайта
//! SRAM и периферии соответствует слово в области-псевдониме: запись 0
//! или 1 в это слово сбрасывает или ставит один бит, одной транзакцией
//! шины. Чтения-изменения-записи в программе нет, и прерывание не может
//! вклиниться между чтением и записью.

// ANCHOR: alias
/// Адрес слова-псевдонима для бита `bit` слова по адресу `addr`.
/// Паника — адрес вне областей bit-band; в константе это ошибка сборки.
///
/// `#[inline]` нужен HAL из другого крейта: без него функция не
/// встраивается без LTO, и каждая смена режима вывода — три вызова.
#[inline]
pub const fn alias(addr: u32, bit: u8) -> u32 {
    assert!(bit < 32, "в слове 32 бита");
    let (region, window) = match addr {
        0x2000_0000..=0x200F_FFFF => (0x2000_0000, 0x2200_0000),
        0x4000_0000..=0x400F_FFFF => (0x4000_0000, 0x4200_0000),
        _ => panic!("адрес вне областей bit-band"),
    };
    // Байт области — 8 бит — 8 слов псевдонима, 32 байта.
    window + (addr - region) * 32 + bit as u32 * 4
}
// ANCHOR_END: alias

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn aliases() {
        // Бит 3 регистра DIR порта F (0x4002_5400) — опыт раздела 27.4.
        assert_eq!(alias(0x4002_5400, 3), 0x424A_800C);
        assert_eq!(alias(0x2000_0000, 0), 0x2200_0000);
        assert_eq!(alias(0x2000_0000, 31), 0x2200_007C);
        assert_eq!(alias(0x2000_0004, 5), 0x2200_0094);
        assert_eq!(alias(0x400F_FFFC, 31), 0x43FF_FFFC);
    }

    #[test]
    #[should_panic(expected = "вне областей bit-band")]
    fn flash_has_no_alias() {
        alias(0x0000_0400, 0);
    }
}
