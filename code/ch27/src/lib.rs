//! Примеры главы 27 «Cortex-M на Rust».
//!
//! - [`exc`] — 27.1: номер исключения из IPSR, значения EXC_RETURN и
//!   кадр, который процессор кладёт в стек при входе в обработчик.
//! - [`prio`] — 27.2: приоритеты NVIC: реализованные биты, вытеснение и
//!   маска BASEPRI.
//! - [`bitband`] — 27.4: адрес слова-псевдонима для атомарной записи
//!   одного бита.
//! - [`hc595`] — 27.5: драйвер сдвигового регистра 74HC595 поверх
//!   `OutputPin` из embedded-hal 1.0.
//! - [`mpu`] — 27.7: регион MPU, запрещающий доступ к дну стека.
//!
//! Чистые функции без обращений к железу: их проверяют тесты на хосте
//! и Miri, а прошивки главы зовут те же функции на Cortex-M3.
