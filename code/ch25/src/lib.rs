//! Примеры главы 25 «Вычисления при компиляции».
//!
//! - [`consts`] — 25.1: `const` и `static`, продвижение в `'static`,
//!   ловушка `const` с внутренней изменяемостью, адреса.
//! - [`const_fn`] — 25.2: что можно в `const fn`, делитель UART при
//!   компиляции, `&mut` и плавающая точка в константах.
//! - [`checks`] — 25.3: `const _: () = assert!(…)`, раскладка как в C,
//!   инварианты таблиц, проверки в обобщённом коде, `compile_error!`.
//! - [`statics`] — 25.4: атомики, `Mutex::new` в `static`, `static mut`
//!   в редакции 2024, `LazyLock` против константной инициализации.
//! - [`tables`] — 25.5: таблица обратных для деления на Cortex-M0, разбор
//!   шестнадцатеричного литерала [`hex!`].
//! - [`project`] — 25.7: сквозной проект, CRC кадра по таблице.
//!
//! Без возможности `std` библиотека собирается для Cortex-M: её таблицы
//! использует прошивка `firmware/ch25-flash`. Программы, которые
//! компилятор отвергает, лежат в doc-тестах `compile_fail`, где есть — с
//! кодом ошибки.
