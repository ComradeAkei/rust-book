//! Раздел 19.1: `asm!` — операнды и опции. Встроенный ассемблер вставляет
//! конкретные инструкции туда, где интринсика нет: счётчик тактов, барьеры,
//! системные регистры. Операнды связывают регистры с переменными Rust
//! (`in`, `out`, `inout`, `lateout`), а опции обещают компилятору, чего блок
//! НЕ делает (`nomem`, `nostack`, `pure`, `preserves_flags`), — на этих
//! обещаниях он оптимизирует вокруг. Соврёшь в опции — UB.

use core::arch::asm;

// ANCHOR: rdtsc
/// Счётчик тактов процессора. `lfence` перед `rdtsc` сериализует конвейер:
/// не даёт внеочередному исполнению утащить чтение счётчика за пределы
/// измеряемого участка. `rdtsc` кладёт 64 бита в `edx:eax`, поэтому две
/// `out`-привязки на фиксированные регистры.
pub fn rdtsc() -> u64 {
    let lo: u32;
    let hi: u32;
    // SAFETY: rdtsc есть на любом x86-64; читает только счётчик тактов в
    // edx:eax, памяти и стека не касается. nomem/nostack — правда; но НЕ
    // pure: значение меняется между вызовами, иначе компилятор слил бы их.
    unsafe {
        asm!("lfence", "rdtsc", out("eax") lo, out("edx") hi, options(nomem, nostack));
    }
    (u64::from(hi) << 32) | u64::from(lo)
}
// ANCHOR_END: rdtsc

// ANCHOR: ops
/// `a * b + c` через `asm!`, на примере операндов и опций. `inout(reg) a =>
/// out` — переменная `a` входит и выходит в одном регистре; `in(reg)` —
/// только вход. `options(pure, nomem, nostack)`: блок не трогает память и
/// стек, а результат зависит только от входов, поэтому компилятор вправе
/// кэшировать и переставлять вызов.
pub fn muladd(a: u64, b: u64, c: u64) -> u64 {
    let out: u64;
    // SAFETY: обе инструкции — чистая арифметика над регистрами, без памяти,
    // стека и побочных эффектов; опции это и обещают.
    unsafe {
        asm!(
            "imul {a}, {b}",
            "add {a}, {c}",
            a = inout(reg) a => out,
            b = in(reg) b,
            c = in(reg) c,
            options(pure, nomem, nostack),
        );
    }
    out
}
// ANCHOR_END: ops

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn muladd_computes() {
        assert_eq!(muladd(3, 4, 5), 17);
        assert_eq!(muladd(0, 99, 7), 7);
    }

    #[test]
    fn rdtsc_advances() {
        let a = rdtsc();
        let b = rdtsc();
        // Счётчик не убывает за короткий промежуток (может совпасть).
        assert!(b >= a);
    }
}
