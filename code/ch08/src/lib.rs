//! Примеры главы 8 «Модули, крейты и сборка».
//!
//! Библиотека собирается и для хоста, и для трёх целей Cortex-M: без
//! возможности `std` она живёт в `no_std`, и её подключает прошивка
//! `firmware/ch08-sections`. Таблицу датчиков и сведения о сборке
//! генерирует `build.rs`. Функции, которые глава разбирает в ассемблере и
//! в таблице символов, помечены `#[inline(never)]`. Фрагменты для книги
//! отмечены парами `ANCHOR: имя` / `ANCHOR_END: имя`.
//!
//! Рядом с крейтом лежат отдельные рабочие пространства, которые тесты
//! собирают через cargo: `typo` (проверка имён в `cfg`), `unify`
//! (унификация возможностей) и `ffi` (типы крейтов), а в `dup` —
//! исходники опыта со столкновением имён без манглинга.
