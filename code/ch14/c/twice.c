/* Глава 14, раздел 14.5: const в C не обещает, что значение не изменится.
 * f может держать неконстантный указатель на то же int, и компилятор
 * обязан прочитать *x второй раз после вызова.
 * Сборка: gcc -O2 -S -masm=intel twice.c */
int twice(const int *x, void (*f)(void))
{
    int a = *x;
    f();
    return a + *x;
}
