/* Глава 12, раздел 12.3: вложенная функция GCC — расширение, которое
 * захватывает локальную переменную. Чтобы её адрес стал обычным
 * указателем на функцию, GCC строит на стеке трамплин: несколько
 * инструкций, которые кладут адрес кадра в регистр и прыгают в тело.
 * Стек для этого должен быть исполняемым. Clang вложенных функций не
 * поддерживает. Запуск: ./nested. */
#include <stdio.h>

static void each(const int *a, int n, void (*f)(int))
{
    for (int i = 0; i < n; i++)
        f(a[i]);
}

int main(void)
{
    int sum = 0;
    void add(int x) { sum += x; } /* захват sum */
    int a[] = {1, 2, 3};
    each(a, 3, add);
    printf("sum = %d\n", sum);
    return 0;
}
