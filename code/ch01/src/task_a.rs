//! Данные задачи 1.A «Предскажите результат `as`».
//!
//! Двенадцать выражений перечислены один раз: макрос превращает их и в
//! строки для сообщений теста, и в код, который их вычисляет. Студент
//! записывает прогнозы в `exercises/ch01/src/a_casts.rs`.
//!
//! Три выражения из двенадцати clippy считает подозрительными, и здесь его
//! предупреждения ожидаемы. Какие именно — подсказка, но смотреть её стоит
//! после того, как прогнозы записаны.
#![expect(
    clippy::cast_nan_to_int,
    clippy::char_lit_as_u8,
    clippy::eq_op,
    reason = "выражения задачи 1.A намеренно странные"
)]

macro_rules! expressions {
    ($($e:expr),* $(,)?) => {
        /// Тексты выражений в порядке номеров задачи.
        pub const EXPRESSIONS: [&str; 12] = [$(stringify!($e)),*];

        /// Значения выражений, расширенные до `i128` без потерь.
        pub fn actual() -> [i128; 12] {
            [$(($e) as i128),*]
        }
    };
}

// ANCHOR: list
expressions![
    300_i32 as u8,
    -1_i8 as u32,
    f64::NAN as i32,
    1e10 as u8,
    -1.9_f64 as u8,
    128_u8 as i8,
    -1_i8 as u8 as i32,
    255_u8 as i8 as i32,
    16_777_217_i32 as f32 as i32,
    u64::MAX as f32 as u64,
    'я' as u8,
    (0.1_f32 + 0.2_f32 == 0.3_f32) as u8,
];
// ANCHOR_END: list
